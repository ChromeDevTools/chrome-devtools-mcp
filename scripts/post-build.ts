import * as fs from 'node:fs';
import * as path from 'node:path';

const GEN_DIR = path.join(process.cwd(), 'out', 'Default', 'gen');

async function main(): Promise<void> {
  // Copy lighthouse bundle that tsc ignores due to lighthouse-devtools-mcp-bundle.d.ts
  const lighthouseBundle = 'src/third_party/lighthouse-devtools-mcp-bundle.js';
  const lighthouseBundleDest = path.join(GEN_DIR, lighthouseBundle);
  fs.mkdirSync(path.dirname(lighthouseBundleDest), {recursive: true});
  fs.copyFileSync(
    path.join(process.cwd(), lighthouseBundle),
    lighthouseBundleDest,
  );

  // Copy issue descriptions generated by GN.
  const descriptionsSrc = path.join(
    GEN_DIR,
    'third_party',
    'devtools-frontend',
    'front_end',
    'models',
    'issues_manager',
    'descriptions',
  );
  const descriptionsDest = path.join(
    GEN_DIR,
    'src',
    'third_party',
    'issue-descriptions',
  );
  fs.cpSync(descriptionsSrc, descriptionsDest, {recursive: true});
}

await main();
